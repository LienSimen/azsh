// Cite: SpellEffects.cpp:1731 EffectApplyAura; :2334 EffectApplyAreaAura (shared route)
export function handleApplyAura(state: HandlerState, raw: RawSpellEffect, slot: number): void {
  const effectType = raw.effect | 0;
  const aura = raw.auraName | 0;

  // Alive gates, optional because a thin bake omits them: a party or pet area aura needs a living
  // target, and a plain aura allows a dead one only for the death-only attributes.
  if (state.ctx.unitTargetIsAlive === false) {
    const isArea =
      effectType === SPELL_EFFECT_APPLY_AREA_AURA_PARTY
      || effectType === SPELL_EFFECT_APPLY_AREA_AURA_PET;
    const deathOk =
      state.ctx.isDeathOnlySpell === true || state.ctx.isDeathPersistentSpell === true;
    if (isArea || !deathOk) {
      state.intents.push({
        kind: 'skip_effect',
        reason: isArea
          ? 'APPLY_AREA_AURA target not alive'
          : 'APPLY_AURA target not alive (not death-only/persistent)',
      });
      return;
    }
  }

  // E27 + aura 3: bake still emits kind `dot` (not persistent_area) for oracle parity.
  // Cite: map-spell-effects.mjs eff === 27 && aura === 3
  const auraHandler = AURA_HANDLERS[aura];
  if (!auraHandler) {
    state.unhandled.push({
      slot,
      effect: effectType,
      auraName: aura,
      reason: `unhandled aura ${aura} (SI3+)`,
    });
    return;
  }
  auraHandler(state, raw, slot, effectType);
}

// Interpret a triggered spell without re-entering the public interpretSpell API (avoids circular import
// with index.ts). Same dispatch as interpretSpell.
export function interpretTriggerSpell(
  spell: SpellDef,
  parentCtx: InterpretContext,
): { effects: SpellEffect[] } {
  const nestedCtx: InterpretContext = {
    ...parentCtx,
    // Nested cast is not a second proc roll of the holder.
    procEvent: undefined,
    spellLookup: undefined,
  };
  const nested = createHandlerState(spell, nestedCtx);
  const rawList = spell.rawEffects;
  if (rawList && rawList.length > 0) {
    for (let slot = 0; slot < rawList.length; slot++) {
      const raw = rawList[slot]!;
      const effect = raw.effect | 0;
      if (!effect) continue;
      const handler = EFFECT_HANDLERS[effect];
      if (!handler) continue;
      handler(nested, raw, slot);
    }
  }
  const final = finalizeResult(nested);
  return { effects: final.effects };
}

